"""Generate src/ui-art.css: image-set sources (1x/2x/3x) + percentage 9-slices for every frame piece (density independent)."""
import os
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__)); FR = os.path.join(HERE, "..", "public", "ui", "frames")
# slice in 1x px: top right bottom left
S = {"panel": (44,44,44,44), "plate": (40,40,40,40), "tile": (44,44,44,44), "bubble": (44,44,44,44), "key": (34,34,34,34),
     "ghost": (30,36,40,36), "gold": (30,38,44,38), "wood": (26,32,38,32), "ribbon": (0,60,0,60)}
out = ["/* GENERATED by tools/frames_css.py - do not edit */", ":root {"]
for n in sorted(os.listdir(FR)):
    if not n.endswith("@1x.png"): continue
    k = n[:-7]; w, h = Image.open(os.path.join(FR, n)).size
    out.append(f"  --fr-{k}: image-set(url(/ui/frames/{k}@1x.png) 1x, url(/ui/frames/{k}@2x.png) 2x, url(/ui/frames/{k}@3x.png) 3x);")
    if k in S:
        t, r, b, l = S[k]; p = lambda v, d: f"{round(v*100/d, 2)}%" if v else "0"
        out.append(f"  --sl-{k}: {p(t,h)} {p(r,w)} {p(b,h)} {p(l,w)};")
out.append("}")
open(os.path.join(HERE, "..", "src", "ui-art.css"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
